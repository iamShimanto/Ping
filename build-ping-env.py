#!/usr/bin/env python3
"""Build Ping production env files on the VPS from reused project envs.
Values NEVER print to stdout: only key names + their source (reused/fresh/
placeholder) are reported. Run on the VPS as root.

Sources:
  SMTP (MailFlyo mailbox) : /var/www/sentia/.env  (SMTP_HOST/PORT/USER/PASS)
  Cloudinary              : /var/www/ali-air-travels/server/.env
  JWT_SECRET              : fresh random (never reused)
  VAPID keys              : fresh, generated by node/web-push (JSON file)
  TURN user/pass          : fresh random (written to turnserver.conf)
  OAuth                   : placeholders (Ping OAuth app not registered yet)
"""
import json
import os
import re
import secrets
import stat
import subprocess
import sys

SENTIA_ENV = "/var/www/sentia/.env"
ALI_ENV = "/var/www/ali-air-travels/server/.env"
PING_DIR = "/opt/ping"
SERVER_ENV = os.path.join(PING_DIR, "apps/server/.env")
WEB_ENV_FILE = "/tmp/ping-web-env"
TURN_PASS_FILE = "/root/ping-turn-pass"
TURN_CONF = "/etc/turnserver.conf"
DOMAIN = "ping.shimantosarkar.dev"


def parse_env(path):
    out = {}
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            v = v.strip().strip('"').strip("'")
            out[k.strip()] = v
    return out


def need(d, key, src):
    if key not in d or not d[key]:
        sys.exit(f"MISSING {key} in {src}")
    return d[key]


def main():
    sentia = parse_env(SENTIA_ENV)
    ali = parse_env(ALI_ENV)

    email_user = need(sentia, "SMTP_USER", SENTIA_ENV)
    email_pass = need(sentia, "SMTP_PASS", SENTIA_ENV)
    smtp_host = need(sentia, "SMTP_HOST", SENTIA_ENV)
    smtp_port = need(sentia, "SMTP_PORT", SENTIA_ENV)
    cloud_name = need(ali, "CLOUDINARY_CLOUD_NAME", ALI_ENV)
    cloud_key = need(ali, "CLOUDINARY_API_KEY", ALI_ENV)
    cloud_secret = need(ali, "CLOUDINARY_API_SECRET", ALI_ENV)

    # Fresh VAPID pair via the repo's own web-push (run from apps/server so
    # node resolves the workspace dependency).
    vapid_json = subprocess.check_output(
        ["node", "-e",
         "console.log(JSON.stringify(require('web-push').generateVAPIDKeys()))"],
        cwd=os.path.join(PING_DIR, "apps/server"), text=True)
    vapid = json.loads(vapid_json)

    jwt_secret = secrets.token_hex(32)
    turn_pass = secrets.token_urlsafe(24)

    server_env = {
        "PORT": "5500",
        "NODE_ENV": "production",
        "MONGODB_URI": "mongodb://127.0.0.1:27020/ping",
        "REDIS_URL": "redis://127.0.0.1:6379/0",
        "JWT_SECRET": jwt_secret,
        "EMAIL_USER": email_user,
        "EMAIL_PASS": email_pass,
        "SMTP_HOST": smtp_host,
        "SMTP_PORT": smtp_port,
        "SMTP_SECURE": "false",
        "CLIENT_URL1": f"https://{DOMAIN}",
        "CLIENT_URL2": f"https://{DOMAIN}",
        "CLIENT_URL3": f"https://{DOMAIN}",
        "CLIENT_URL4": f"https://{DOMAIN}",
        "SERVER_URL": f"https://{DOMAIN}",
        "CLOUDINARY_CLOUD_NAME": cloud_name,
        "CLOUDINARY_API_KEY": cloud_key,
        "CLOUDINARY_API_SECRET": cloud_secret,
        "VAPID_PUBLIC_KEY": vapid["publicKey"],
        "VAPID_PRIVATE_KEY": vapid["privateKey"],
        "VAPID_EMAIL": f"mailto:{email_user}",
        # Placeholders: Ping has no Google/GitHub OAuth app registered yet.
        # OAuth login will fail until Sir registers one with callbacks
        # https://ping.shimantosarkar.dev/api/v1/auth/google/callback
        # https://ping.shimantosarkar.dev/api/v1/auth/github/callback
        "GOOGLE_CLIENT_ID": "pending-registration",
        "GOOGLE_CLIENT_SECRET": "pending-registration",
        "GITHUB_CLIENT_ID": "pending-registration",
        "GITHUB_CLIENT_SECRET": "pending-registration",
    }
    with open(SERVER_ENV, "w") as f:
        for k, v in server_env.items():
            f.write(f"{k}={v}\n")
    os.chmod(SERVER_ENV, 0o600)

    web_env = {
        "VITE_API_URL": f"https://{DOMAIN}",
        "VITE_SOCKET_URL": f"https://{DOMAIN}",
        "VITE_VAPID_PUBLIC_KEY": vapid["publicKey"],
        "VITE_WEBRTC_URL": f"turn:{DOMAIN}:3478",
        "VITE_WEBRTC_USERNAME": "ping",
        "VITE_WEBRTC_CREDENTIAL": turn_pass,
    }
    with open(WEB_ENV_FILE, "w") as f:
        for k, v in web_env.items():
            f.write(f"{k}={v}\n")
    os.chmod(WEB_ENV_FILE, 0o600)

    with open(TURN_PASS_FILE, "w") as f:
        f.write(turn_pass + "\n")
    os.chmod(TURN_PASS_FILE, 0o600)

    turn_conf = f"""# coturn for Ping (WebRTC relay) — generated by build-ping-env.py
listening-port=3478
listening-ip=0.0.0.0
relay-ip=72.60.233.97
external-ip=72.60.233.97
realm={DOMAIN}
server-name={DOMAIN}
fingerprint
lt-cred-mech
user=ping:{turn_pass}
min-port=49152
max-port=65535
log-file=/var/log/turnserver.log
no-stdout-log
"""
    with open(TURN_CONF, "w") as f:
        f.write(turn_conf)
    os.chmod(TURN_CONF, 0o600)

    report = [
        ("PORT/NODE_ENV/MONGODB_URI/REDIS_URL", "deploy config (dedicated mongod :27020)"),
        ("JWT_SECRET", "FRESH random hex"),
        ("EMAIL_USER/EMAIL_PASS/SMTP_HOST/SMTP_PORT", "REUSED from /var/www/sentia/.env (MailFlyo mailbox)"),
        ("SMTP_SECURE=false", "STARTTLS on 587"),
        ("CLIENT_URL1-4/SERVER_URL", f"https://{DOMAIN}"),
        ("CLOUDINARY_CLOUD_NAME/API_KEY/API_SECRET", "REUSED from /var/www/ali-air-travels/server/.env"),
        ("VAPID_PUBLIC_KEY/VAPID_PRIVATE_KEY", "FRESH via web-push generateVAPIDKeys"),
        ("VAPID_EMAIL", "mailto: reused mailbox"),
        ("GOOGLE_/GITHUB_ CLIENT_ID/SECRET", "PLACEHOLDER pending-registration (no Ping OAuth app yet)"),
        ("TURN user ping", "FRESH, in /etc/turnserver.conf + /root/ping-turn-pass"),
    ]
    print("PING ENV BUILT (values not shown):")
    for k, s in report:
        print(f"  {k}  <- {s}")
    print(f"  server .env: {SERVER_ENV} (0600)")
    print(f"  web env: {WEB_ENV_FILE} (0600)")


if __name__ == "__main__":
    main()
